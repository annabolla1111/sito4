            <p>“Cercavamo un nome per un’associazione che desse l’idea di persone e talenti diversi che unendosi creano qualcosa di nuovo, ma ci premeva che questo “nuovo nato” potesse ulteriormente trasformarsi. Qualcosa che esprimesse movimento, possibilità, divenire, e armonia… Qualcosa che fosse più dell’unione delle parti in cui ogni parte è indispensabile ma non basta da sola, e nello stesso tempo che si trasformasse fluendo…</p>

<p>Anche il modo in cui abbiamo trovato il nome dell’associazione in una serata di brainstorming è parte integrante di quello che vogliamo realizzare: un “luogo” di possibilità, in cui diversi talenti possano mettersi insieme per creare una melodia che esprima e racconti qualcosa del mondo e al mondo ritorni.
</p>
<p>Accordo è un’associazione di Coterapia. Si può parlare di Coterapia quando diverse figure professionali si uniscono  per occuparsi INSIEME del disagio di una persona. Per fare questo però è indispensabile condividere alcuni assunti circa l’idea di salute e malattia:</p>
</p>
<ul class="elenco">
    <li>L’idea che la  salute sia una condizione di equilibrio tra i sistemi interno (psichico e fisico), relazionale e ambientale di ogni persona.</li>
    <li>L’idea che l’equilibrio tra questi sistemi per definizione non possa essere statico, in quanto tutti questi sistemi sono in movimento e in divenire al loro interno e s’influenzano reciprocamente</li>
    <li>L’idea che la malattia sia sostanzialmente una mancanza di equilibrio che dura più o meno nel tempo e che si viene a creare per qualche motivo presente o passato, interno od esterno</li>
    <li>L’idea che una temporanea perdita di equilibrio possa trasformarsi nel raggiungimento di un equilibrio “dinamicamente” più stabile</li>
    <li>L’idea che l’equilibrio raggiunto o raggiungibile non possa che essere soggettivo, e quindi che per “curare” si debba necessariamente orientare ogni tipo di intervento rispetto ai parametri individuali di QUELLA persona, facendone il più possibile parte attiva del progetto.</li>
</ul>

<p>Immaginiamo la vita come il suono di una melodia individuale che si fonde con tutte le altre, di tutti i viventi, dell’ambiente, della terra, del cosmo… una melodia che si crea continuamente, come… come una gigantesca Jam Session!

Immaginiamo quindi la salute come la condizione  in cui si riesce a suonare, esprimere se stessi, a volte con un assolo, a volte suonando con altri, tanti o pochi…

La malattia appare allora come la condizione in cui non si riesce o non riesce più a suonare la propria melodia; e le cause possono essere interne o esterne, presenti o passate; (fisiche, psichiche, relazionali, ambientali…)</p>

<p>Ecco che l’obiettivo della cura può essere quello di aiutare la persona a suonare ancora, o suonare meglio…

E se riusciamo a vedere la vita, le relazioni tra le persone, e quindi anche la terapia, come una continua, grande o piccola “Jam Session”, questo naturalmente vale anche  per la coterapia. Questo è lo spirito di “Accordo”.

Di cosa ci occupiamo: di diffondere la cultura della Coterapia, della collaborazione tra diverse discipline, nell’ambito della Cura della Persona, attraverso l’elaborazione e/o l’attuazione di progetti di ricerca, sperimentazione e formazione.”</p>

<p>Questo scrivevamo la sera del 6 dicembre 2007, in una serata di brainstorming a casa di Laura, attuale vicepresidente di Accordo. Da allora sono passati quasi quindici anni, e il Progetto Windhorse è al momento il fulcro del nostro lavoro.
La nostra collaborazione con i gruppi che nel mondo si occupano della diffusione di questo approccio è cresciuta negli ultimi anni, orientando sempre più le attività di Accordo in questa direzione. Gli scambi con gli altri Centri avvengono sia mensilmente, durante le supervisioni dei progetti in corso e gli incontri del Windhorse World Council, sia attraverso la partecipazione attiva all’organizzazione delle conferenze internazionali Windhorse di Vienna nel 2014 e di Boulder, Colorado, nel 2019. Accordo è parte attiva del Windhorse International Network
In particolare collaboriamo con il centro Windhorse di Vienna e con il Windhorse Community Center di Boulder.</p>
