<section class="progetti">
        <h2>Progetto Windhorse</h2>
        <p>Il “Progetto Windhorse” venne sperimentato per la prima volta nel 1981 a Boulder, in Colorado,  da Edward Podvoll e altri colleghi della “Naropa University”, con la creazione di una equipe terapeutica multiprofessionale intorno ad una paziente precedentemente istituzionalizzata. L’idea alla base era quella di creare un ambiente “ad hoc” che potesse realmente favorire il recupero e la guarigione di quella specifica persona attraverso una attenzione e un accompagnamento alle attività domestiche, lo stabilirsi di sane relazioni interpersonali, il recupero progressivo di attività e ritmi giornalieri, oltre a frequenti sedute di psicoterapia, accompagnate da farmacoterapia durante le fasi acute. (Recovering Sanity, Shambala Pubblications 2003, precedente traduzione italiana “La seduzione della pazzia). Successivamente, nel 1990, con altri colleghi E. Podvoll creò la Windhorse Community Services (WCS).</p>

<p>Ad oggi la rete dei centri Windhorse, di cui anche Accordo è parte, si è diffusa in vari stati in Europa e USA, e il prezioso lavoro del Windhorse Legacy Project permette, attraverso l’archivio, di condividere più di quarant’anni di preziosa esperienza.</p>

<p>Ispirato alla psicologia sia occidentale sia buddista, l’approccio Windhorse implica un team di terapeuti esperti che operano da vicino sul paziente nel suo ambiente domiciliare. Il progetto windhorse è oggi rivolto a persone con una vasta gamma di disturbi psichici: disturbi della forma e del contenuto del pensiero, dell’umore e di personalità, disturbi alimentari, abuso di sostanze. Sono possibili anche progetti dedicate ad anziani e di accompagnamento nelle malattie in fase terminale.</p>

<p>Mentre il modello medico biologico pone le basi del trattamento delle forme gravi di disturbo mentale sull’utilizzo a lungo termine di farmaci antipsicotici, l’approccio windhorse sottolinea la necessità di trattare le persone secondo una prospettiva olistica, in cui le dimensioni biologica, psicologica, sociale e spirituale vengano prese in considerazione con l’intenzione di aiutare i pazienti a correggere lo squilibrio che è al centro dello stato di disagio.</p>

<p>La presa in carico non può prescindere dalla considerazione delle altre persone conviventi, e il benessere ricercato è quello di tutto il nucleo, i cui componenti sono coinvolti in incontri periodici con le equipe.</p>

<p>Tali incontri si svolgono secondo modalità concordate, in cui vigono gli stessi principi di ascolto di sé e dell’altro che si praticano, sia durante le sessioni di psicoterapia Windhorse (anche queste a domicilio), sia durante i turni di Basic Attendance. Si viene così a creare un “ambiente Windhorse”, una sorta di comunità dove l’ascolto reciproco è coltivato.</p>

<p>L’opzione di supporto domiciliare può rappresentare una valida alternativa per parte dei nuovi ingressi in strutture residenziali, garantendo quella flessibilità di supporto che raramente le strutture sono in grado di offrire.</p>
<p>Si rivela altresì efficace nella delicata fase di dimissione dalle stesse strutture per un accompagnamento alla riabilitazione con una ripresa o un raggiungimento delle abilità quotidiane in termini di autosufficienza, indipendenza, cura di sé e qualità della vita.</p>

<p>Per ulteriori informazioni sui progetti Windhorse <a href="contatti.php">contattateci</a>.

